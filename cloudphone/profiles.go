type CreateRequestDataItem struct {
	// Android version for this phone: Android 9 through Android 16. Omitted values use
	// CreateRequest.MobileType.
	MobileType string `json:"mobileType,omitempty"`
	// Cloud Phone Name. Required.
	ProfileName string `json:"profileName,omitempty"`
	// Proxy URL using http, https, or socks5. Use "LocalNetwork" without a proxy and enable
	// the desktop client network extension.
	ProxyInformation string `json:"proxyInformation,omitempty"`
	// Proxy refresh url.
	RefreshURL string `json:"refreshUrl,omitempty"`
	// Proxy detection channel, takes effect when using proxyInformation, 1-ip-api,
	// 2-IP2Location, default is 2.
	ProxyQueryChannel *int `json:"proxyQueryChannel,omitempty"`
	// The serial number of the added proxy.
	ProxyNumber *int `json:"proxyNumber,omitempty"`
	// Saved dynamic proxy, can be set
	// IPHTML/kookeey/Luminati(BrightData)/rolaip/Proxyma/DECODO/NodeMaven/kookeeyMobile/GProxyResidential.
	DynamicProxy string `json:"dynamicProxy,omitempty"`
	// Dynamic proxy country, required when specifying a dynamic proxy. Please refer to the
	// list of dynamic proxy country codes for possible values.
	// (https://singapore-upgrade.geelark.com/apiResource/proxy-country.txt).
	DynamicProxyLocation string `json:"dynamicProxyLocation,omitempty"`
	// Cloud phone region. If not specified, it will follow the proxy. Please refer to Cloud
	// Phone Region List (https://singapore-upgrade.geelark.com/apiResource/region.txt).
	MobileRegion string `json:"mobileRegion,omitempty"`
	// State. Only the United States is currently supported. Please refer to State-City Mapping
	// Table (https://singapore-upgrade.geelark.com/apiResource/timezone.json).
	MobileProvince string `json:"mobileProvince,omitempty"`
	// City. Only the United States is currently supported. Please refer to State-City Mapping
	// Table (https://singapore-upgrade.geelark.com/apiResource/timezone.json).
	MobileCity string `json:"mobileCity,omitempty"`
	// Cloud phone language. Use "baseOnIP" to follow the proxy, or "default" (also used when
	// omitted) for English. Custom values:
	// https://singapore-upgrade.geelark.com/apiResource/language.txt.
	MobileLanguage string `json:"mobileLanguage,omitempty"`
	// Group name, if it does not exist, create a new one automatically.
	ProfileGroup string `json:"profileGroup,omitempty"`
	// Tag name, if it does not exist, create a new one automatically.
	ProfileTags []string `json:"profileTags,omitempty"`
	// Remark.
	ProfileNote string `json:"profileNote,omitempty"`
	// Mobile phone brand, get from the brand list API
	// (https://open.geelark.com/api/phone-brand-list) or custom brand list API
	// (https://open.geelark.com/api/phone-brand-teamList), and the brand model should be
	// transmitted at the same time.
	SurfaceBrandName string `json:"surfaceBrandName,omitempty"`
	// Mobile phone model, get from the brand list API
	// (https://open.geelark.com/api/phone-brand-list) or custom brand list API
	// (https://open.geelark.com/api/phone-brand-teamList), and the brand model should be
	// transmitted at the same time.
	SurfaceModelName string `json:"surfaceModelName,omitempty"`
	// Whether it is the team brand model. If true, the brand model must also be passed.
	IsTeamBrand *bool `json:"isTeamBrand,omitempty"`
	// Networking. 0-Wi-Fi, 1-Mobile. Only supported on Andorid 12/Andorid 13/Andorid
	// 14/Andorid 15/Andorid 16. Default to mobile network.
	NetType *int `json:"netType,omitempty"`
	// Mobile phone number, automatically generated if empty.
	PhoneNumber string `json:"phoneNumber,omitempty"`
	// Device name, automatically generated by default, not supported in Android 9/11.
	PhoneName string `json:"phoneName,omitempty"`
	// wifi name, limit: 16 characters.
	WiFiID string `json:"wifiId,omitempty"`
	// GProxy protocol type: 1 socks5，2 http. Default socks5.
	Protocol *int `json:"protocol,omitempty"`
	// GProxy Session Type: 1 Sticky 2 Rotating, Default 1.
	SessionType *int `json:"sessionType,omitempty"`
	// GProxy FilterMode: 0 MaxPoolSize 1 Quality 2 QualitySpeed 3 Speed, Default.
	FilterMode *int `json:"filterMode,omitempty"`
}

